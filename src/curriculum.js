export function getLesson(id, grade, lang = "en") {
  if (!data[id]) throw new RangeError("Unknown subject");
  if (![6, 7, 8, 9, 10].includes(Number(grade)))
    throw new RangeError("Grade must be 6–10");
  const d = data[id][Number(grade) - 6],
    hi = lang === "hi";
  const convert = (raw, key, index) => ({
    id: `${id}-${grade}-${key}-${index}`,
    prompt: localise(raw.prompt, hi),
    options: raw.options.map((o) => localise(o, hi)),
    answer: raw.answer,
    explanation: d[hi ? 3 : 2],
  });
  const extra = extensions[id][Number(grade) - 6];
  const practice = [0, 1].map((index) => ({
    id: `${id}-${grade}-practice-${index}`,
    prompt: hi
      ? practiceHindi[id][Number(grade) - 6][index]
      : d[index === 0 ? 4 : 7],
    options: d[index === 0 ? 5 : 8].map((o) => localise(o, hi)),
    answer: d[index === 0 ? 6 : 9],
    explanation: d[hi ? 3 : 2],
  }));
  const foundation = extra
    .slice(0, 2)
    .map((q, i) => convert(q, "foundation", i));
  const stretch = extra.slice(2, 4).map((q, i) => convert(q, "stretch", i));
  const relabel = (q, key, i) => ({ ...q, id: `${id}-${grade}-${key}-${i}` });
  return {
    id,
    grade: Number(grade),
    name: names[id][hi ? 1 : 0],
    title: d[hi ? 1 : 0],
    intro: d[hi ? 3 : 2],
    explanation: d[hi ? 3 : 2],
    hint: hi
      ? "नियम पढ़ें, फिर प्रत्येक विकल्प की जाँच करें।"
      : "Read the rule, then check each option.",
    prerequisites: [d[hi ? 11 : 10]],
    questions: { foundation, practice, stretch },
    diagnostic: [foundation[0], foundation[1], practice[0]].map((q, i) =>
      relabel(q, "diagnostic", i),
    ),
    test: [stretch[0], stretch[1], convert(extra[4], "novel", 0)].map((q, i) =>
      relabel(q, "test", i),
    ),
  };
}
export function recommend(history = []) {
  const last = history.slice(-2);
  if (last.length === 2 && last.every((h) => !h.correct))
    return {
      level: "foundation",
      pace: "revisit",
      reason:
        "Revisit the prerequisite with your teacher, then try a guided example.",
    };
  if (last.length === 2 && last.every((h) => h.correct))
    return {
      level: "stretch",
      pace: "faster",
      reason: "Two secure answers: try an extension challenge.",
    };
  return {
    level: "practice",
    pace: "steady",
    reason: "Keep practising with a worked example and a useful hint.",
  };
}
export function checkpointMastery(attempts = []) {
  if (!attempts.length) return 0;
  return Math.round(
    (attempts.filter((a) => a.correct).length / attempts.length) * 100,
  );
}
